"""Generatore di profili ICC v2 matrice/TRC, deterministico (data fissa nell'header).

Serve in due casi:
- HEIC da iPhone che dichiarano il colore con nclx (es. primarie P3) invece che con un ICC:
  per preservare il colore nel master PNG/TIFF serve un ICC equivalente;
- test con profili reali Display P3 / Adobe RGB (ImageCms crea solo sRGB/LAB/XYZ).
"""

from __future__ import annotations

import struct
from functools import cache
from typing import Literal

import numpy as np
from numpy.typing import NDArray

Primaries = tuple[tuple[float, float], tuple[float, float], tuple[float, float]]
TrcKind = Literal["srgb", "adobe"]

D65 = (0.3127, 0.3290)
D50_XYZ = (0.9642, 1.0, 0.8249)

PRIMARIES: dict[str, Primaries] = {
    "srgb": ((0.640, 0.330), (0.300, 0.600), (0.150, 0.060)),
    "display_p3": ((0.680, 0.320), (0.265, 0.690), (0.150, 0.060)),
    "adobe_rgb": ((0.640, 0.330), (0.210, 0.710), (0.150, 0.060)),
}

_BRADFORD = np.array(
    [[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]]
)


def _xy_to_xyz(x: float, y: float) -> NDArray[np.float64]:
    return np.array([x / y, 1.0, (1 - x - y) / y])


def rgb_to_xyz_d50(primaries: Primaries, white: tuple[float, float] = D65) -> NDArray[np.float64]:
    """Matrice RGB lineare -> XYZ (D50, adattamento Bradford), come nei colorant ICC."""
    cols = np.stack([_xy_to_xyz(*p) for p in primaries], axis=1)
    w = _xy_to_xyz(*white)
    s = np.linalg.solve(cols, w)
    m = cols * s
    src = _BRADFORD @ w
    dst = _BRADFORD @ np.array(D50_XYZ)
    adapt = np.linalg.inv(_BRADFORD) @ np.diag(dst / src) @ _BRADFORD
    return np.asarray(adapt @ m)


def _s15f16(v: float) -> bytes:
    return struct.pack(">i", round(v * 65536))


def _xyz_tag(xyz: tuple[float, float, float] | NDArray[np.float64]) -> bytes:
    return b"XYZ " + b"\0" * 4 + b"".join(_s15f16(float(c)) for c in xyz)


def _curv_tag(kind: TrcKind) -> bytes:
    if kind == "adobe":  # gamma 563/256, esattamente rappresentabile in u8Fixed8
        return b"curv" + b"\0" * 4 + struct.pack(">IH", 1, 563)
    n = 1024
    v = np.arange(n) / (n - 1)
    lin = np.where(v <= 0.04045, v / 12.92, ((v + 0.055) / 1.055) ** 2.4)
    table = np.clip(np.rint(lin * 65535), 0, 65535).astype(">u2").tobytes()
    return b"curv" + b"\0" * 4 + struct.pack(">I", n) + table


def _desc_tag(text: str) -> bytes:
    a = text.encode("ascii") + b"\0"
    return (
        b"desc"
        + b"\0" * 4
        + struct.pack(">I", len(a))
        + a
        + struct.pack(">II", 0, 0)
        + struct.pack(">HB", 0, 0)
        + b"\0" * 67
    )


def _text_tag(text: str) -> bytes:
    return b"text" + b"\0" * 4 + text.encode("ascii") + b"\0"


def _pad4(b: bytes) -> bytes:
    return b + b"\0" * (-len(b) % 4)


def build_matrix_profile(description: str, primaries: Primaries, trc: TrcKind) -> bytes:
    m = rgb_to_xyz_d50(primaries)
    curv = _curv_tag(trc)
    tags = [
        (b"desc", _desc_tag(description)),
        (b"cprt", _text_tag("Generated by posa")),
        (b"wtpt", _xyz_tag(D50_XYZ)),
        (b"rXYZ", _xyz_tag(m[:, 0])),
        (b"gXYZ", _xyz_tag(m[:, 1])),
        (b"bXYZ", _xyz_tag(m[:, 2])),
        (b"rTRC", curv),
        (b"gTRC", curv),
        (b"bTRC", curv),
    ]
    table_size = 4 + 12 * len(tags)
    offset = 128 + table_size
    entries, data = [], b""
    shared: dict[bytes, int] = {}
    for sig, body in tags:
        if body in shared:  # i tre TRC condividono gli stessi dati
            entries.append(struct.pack(">4sII", sig, shared[body], len(body)))
            continue
        shared[body] = offset + len(data)
        entries.append(struct.pack(">4sII", sig, offset + len(data), len(body)))
        data += _pad4(body)
    size = 128 + table_size + len(data)
    header = (
        struct.pack(">I", size)
        + b"lcms"
        + struct.pack(">I", 0x02100000)
        + b"mntr"
        + b"RGB "
        + b"XYZ "
        + struct.pack(">6H", 2024, 1, 1, 0, 0, 0)  # data fissa: profilo deterministico
        + b"acsp"
        + b"\0" * 4
        + struct.pack(">I", 0)
        + b"\0" * 4
        + b"\0" * 4
        + b"\0" * 8
        + struct.pack(">I", 0)
        + b"".join(_s15f16(c) for c in D50_XYZ)
        + b"\0" * 4
        + b"\0" * 16
        + b"\0" * 28
    )
    assert len(header) == 128
    return header + struct.pack(">I", len(tags)) + b"".join(entries) + data


@cache
def display_p3() -> bytes:
    return build_matrix_profile("Display P3 (posa)", PRIMARIES["display_p3"], "srgb")


@cache
def adobe_rgb() -> bytes:
    return build_matrix_profile(
        "Adobe RGB (1998) compatible (posa)", PRIMARIES["adobe_rgb"], "adobe"
    )


@cache
def srgb() -> bytes:
    return build_matrix_profile("sRGB IEC61966-2.1 (posa)", PRIMARIES["srgb"], "srgb")
